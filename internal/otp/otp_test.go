func TestExtractKeywords(t *testing.T) {
	keywords := []string{
		"验证码", "校验码", "确认码", "动态码", "动态密码", "动态口令", "一次性密码", "一次性口令",
		"登录码", "登陆码", "注册码", "安全码", "授权码",
		"verification code", "authentication code", "security code", "confirmation code", "login code",
		"authorization code", "one-time code", "one time code", "one-time password", "one time password", "passcode", "OTP",
	}
	for _, keyword := range keywords {
		t.Run(keyword, func(t *testing.T) {
			for _, body := range []string{keyword + ": aB12Cd", "aB12Cd (" + strings.ToUpper(keyword) + ")"} {
				if got := Extract(body); got != "aB12Cd" {
					t.Fatalf("Extract(%q) = %q, want aB12Cd", body, got)
				}
			}
		})
	}
}

func TestExtractNegativeLabels(t *testing.T) {
	labels := []string{
		"手机号", "电话", "尾号", "订单号", "流水号", "运单号", "取件码", "提货码", "券码", "优惠码", "错误码",
		"phone", "mobile", "order number", "tracking number", "pickup code", "coupon code", "error code",
	}
	for _, label := range labels {
		t.Run(label, func(t *testing.T) {
			for _, connector := range []string{": ", "为", "是：", " is ", "　"} {
				body := "验证码已发送，" + label + connector + "A1B2C3"
				if got := Extract(body); got != "" {
					t.Fatalf("Extract(%q) = %q, want empty", body, got)
				}
			}
		})
	}
}

func TestExtractClauseBoundaries(t *testing.T) {
	for _, punctuation := range []string{"。", "！", "？", "!", "?", "；", ";", "\n\n"} {
		body := "验证码已发送" + punctuation + "123456"
		if got := Extract(body); got != "" {
			t.Errorf("Extract(%q) = %q, want empty", body, got)
		}
	}
}
