// 用例都是真实短信的常见句式。宁可漏提也不能把金额/年份/手机号当验证码。
func TestExtract(t *testing.T) {
	cases := []struct {
		name string
		body string
		want string
	}{
		// 命中：关键词在前
		{"全角冒号", "【淘宝】验证码：483921，请勿泄露给他人", "483921"},
		{"是字衔接", "您的验证码是5829135，10分钟内有效", "5829135"},
		{"空格分隔", "【微信】 校验码 556677，十分钟内有效", "556677"},
		{"动态密码", "您的动态密码为 246810，请勿告知他人", "246810"},
		{"英文关键词", "Your verification code is 582913", "582913"},
		{"英文简写", "ShopApp code: 123456. Do not share it.", "123456"},

		// 命中：数字在前
		{"是您的验证码", "483921 是您的验证码，转发给他人将导致账号被盗", "483921"},
		{"括号标注", "483921（验证码）如非本人操作请忽略", "483921"},
		{"英文数字在前", "123456 is your code", "123456"},

		// 命中：兜底（有验证字样、无结构线索）
		{"关键词离得远", "您的验证码已发送至您的手机，码为 483921 请注意查收", "483921"},
		{"英文兜底", "G-483921 is your Google verification code", "483921"},

		// 拒绝：不该提取的
		{"纯金额", "您的话费余额为1234元，感谢使用", ""},
		{"无任何线索", "明天下午3点在会议室开会，请准时参加", ""},
		{"订单号无验证字样", "您的订单202610311234已发货，预计三天送达", ""},
		{"验证码后无真码", "验证码已发送，10分钟内有效，请及时输入", ""},
		{"打码手机号尾巴", "验证码已发送到138****1234，请查收", ""},
		{"关键词接长数字", "您的验证码已发送，请联系13800138000咨询", ""},
		{"关键词接超长数字", "验证码1234567890123格式有误请重试", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := Extract(c.body); got != c.want {
				t.Fatalf("Extract(%q) = %q, want %q", c.body, got, c.want)
			}
		})
	}
}

func TestExtractEmpty(t *testing.T) {
	if got := Extract(""); got != "" {
		t.Fatalf("Extract(\"\") = %q, want \"\"", got)
	}
}

